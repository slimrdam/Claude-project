const LANGS = ["fr", "en"];
const KEY = "thesis.lang";
let lang = "fr";

try {
  const saved = localStorage.getItem(KEY);
  if (saved && LANGS.includes(saved)) lang = saved;
  else if ((navigator.language || "").toLowerCase().startsWith("en")) lang = "en";
} catch (e) { /* private mode: fall through to the default */ }

const missing = new Set();

function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]);
  if (s === undefined) {
    s = DICT.en[key];
    if (s === undefined) {
      if (!missing.has(key)) { missing.add(key); console.warn("i18n: missing key", key); }
      return key;
    }
  }
  if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  return s;
}

function apply(scope) {
  const el = scope || document;
  el.querySelectorAll("[data-i18n]").forEach(n => { n.textContent = t(n.dataset.i18n); });
  el.querySelectorAll("[data-i18n-html]").forEach(n => { n.innerHTML = t(n.dataset.i18nHtml); });
  el.querySelectorAll("[data-i18n-aria]").forEach(n => { n.setAttribute("aria-label", t(n.dataset.i18nAria)); });
  document.documentElement.lang = lang;
}

function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch (e) { /* not fatal */ }
  apply();
  window.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}


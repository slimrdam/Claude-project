# =============================================================================
# SBET vs ETH mNAV dashboard - one-shot publisher
#
# Creates a GitHub repo, pushes the dashboard, enables Pages, runs the refresh
# workflow once, waits for it to go green, and prints the live URL.
#
#   ./bootstrap.sh [repo-name]        default: sbet-eth-mnav
#
# Idempotent-ish: refuses to clobber an existing repo rather than guessing.
# Every payload file is embedded below as base64 so this script is the only
# thing you need.
# =============================================================================
set -euo pipefail

REPO="${1:-sbet-eth-mnav}"
WORKDIR="${WORKDIR:-$PWD/$REPO}"

say()  { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[33m    ! %s\033[0m\n' "$*"; }
die()  { printf '\n\033[31mFAILED: %s\033[0m\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- 1. preflight
say "Checking prerequisites"
for c in git gh python3; do
  command -v "$c" >/dev/null || die "$c is not installed."
done

if ! gh auth status >/dev/null 2>&1; then
  if [ -n "${GITHUB_TOKEN:-}" ]; then
    echo "$GITHUB_TOKEN" | gh auth login --with-token \
      || die "GITHUB_TOKEN was rejected. It needs 'repo' and 'workflow' scopes."
  else
    die "Not authenticated. Either:
  (a) run: gh auth login   - pick GitHub.com, HTTPS, 'Login with a web browser',
      then open github.com/login/device on your phone and enter the code; or
  (b) create a token at github.com/settings/tokens with 'repo' + 'workflow'
      scopes and re-run with: GITHUB_TOKEN=ghp_xxx ./bootstrap.sh"
  fi
fi

OWNER="$(gh api user --jq .login)" || die "Could not read your GitHub account."
echo "    authenticated as $OWNER"

# 'workflow' scope is required to push .github/workflows/ over HTTPS
if ! gh auth status 2>&1 | grep -qi 'workflow'; then
  warn "Your token may lack the 'workflow' scope. If the push is rejected, run:"
  warn "  gh auth refresh -h github.com -s workflow"
fi

if gh repo view "$OWNER/$REPO" >/dev/null 2>&1; then
  die "$OWNER/$REPO already exists. Pass a different name: ./bootstrap.sh my-name"
fi

# ---------------------------------------------------------------- 2. materialise
say "Writing files to $WORKDIR"
mkdir -p "$WORKDIR/.github/workflows"
cd "$WORKDIR"

emit() {  # emit <path> <<< base64
  python3 -c "import base64,sys,pathlib
p=pathlib.Path(sys.argv[1]); p.parent.mkdir(parents=True,exist_ok=True)
p.write_bytes(base64.b64decode(sys.stdin.read()))" "$1"
}

